## Bust crops of a character sheet's first frame: (sheet, output name).
BUSTS = [
    ("normaali_mies_32.png", "customer.png"),
    ("agentti_32.png", "lvv.png"),
    ("barbaari_32.png", "bar_fight.png"),
    ("saksalainen_turisti_32.png", "verboten.png"),
]
BUST_SIZE = 20


def draw(pixel_map: str) -> Image.Image:
    rows = [row for row in pixel_map.strip("\n").split("\n")]
    image = Image.new("RGBA", (32, 32))
    top = (32 - len(rows)) // 2
    for y, row in enumerate(rows):
        for x, char in enumerate(row):
            image.putpixel((x, y + top), PALETTE[char])
    return image


def bust(sheet: str) -> Image.Image:
    frame = Image.open(CHARACTERS / sheet).convert("RGBA").crop((0, 0, 32, 32))
    left, top, right, _bottom = frame.getbbox()
    center = (left + right) // 2
    crop = frame.crop((center - BUST_SIZE // 2, top - 1, center + BUST_SIZE // 2, top - 1 + BUST_SIZE))
    image = Image.new("RGBA", (32, 32))
    image.paste(crop.resize((BUST_SIZE, BUST_SIZE), Image.NEAREST), ((32 - BUST_SIZE) // 2, (32 - BUST_SIZE) // 2))
    return image


def fit_to_icon(path: Path) -> Image.Image:
    """Centres a sprite in 32x32, cutting its top if it is taller (the brush handle)."""
    sprite = Image.open(path).convert("RGBA")
    sprite = sprite.crop((0, max(0, sprite.height - 32), sprite.width, sprite.height))
    image = Image.new("RGBA", (32, 32))
    image.paste(sprite, ((32 - sprite.width) // 2, (32 - sprite.height) // 2))
    return image


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    draw(MUG).save(OUT / "beer_mug.png")
    draw(COINS).save(OUT / "coins.png")
    draw(TROPHY).save(OUT / "trophy.png")
    fit_to_icon(BRUSH).save(OUT / "wash.png")
    for sheet, name in BUSTS:
        bust(sheet).save(OUT / name)


if __name__ == "__main__":
    main()
